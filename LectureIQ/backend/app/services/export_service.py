import json
from typing import Dict, Any

class ExportService:
    @staticmethod
    def to_markdown(lecture_data: Dict[str, Any]) -> str:
        """Exports the lecture, summaries, notes, flashcards, and quizzes into clean Markdown."""
        md = []
        md.append(f"# 🎓 LectureIQ Study Package: {lecture_data.get('title', 'Lecture')}")
        md.append(f"**Subject:** {lecture_data.get('subject', 'General')} | **Source Type:** {lecture_data.get('source_type', 'Text')}")
        md.append(f"**Generated by LectureIQ on:** {lecture_data.get('created_at', '')}\n")
        md.append("---\n")

        # Summary
        md.append("## 📝 Executive Summary\n")
        md.append(lecture_data.get("executive_summary") or "No summary generated yet.")
        md.append("\n### Key Takeaways\n")
        takeaways = lecture_data.get("key_takeaways", [])
        if isinstance(takeaways, str):
            try:
                takeaways = json.loads(takeaways)
            except Exception:
                takeaways = [takeaways]
        for t in takeaways:
            md.append(f"- {t}")
        md.append("\n---\n")

        # Smart Notes
        md.append("## 📚 Topic-Wise Smart Notes\n")
        md.append(lecture_data.get("smart_notes") or "No smart notes generated yet.")
        md.append("\n---\n")

        # Flashcards
        md.append("## 🧠 Revision Flashcards\n")
        cards = lecture_data.get("flashcards", [])
        for idx, card in enumerate(cards, 1):
            md.append(f"### Card {idx}: {card.get('concept', 'Concept')}")
            md.append(f"**Q:** {card.get('question')}")
            md.append(f"**A:** {card.get('answer')}")
            md.append(f"*Difficulty: {card.get('difficulty')} | Status: {card.get('mastery_status', 'learning')}*\n")
        md.append("---\n")

        # Quizzes
        md.append("## ❓ Practice Quiz Questions\n")
        quizzes = lecture_data.get("quizzes", [])
        for idx, q in enumerate(quizzes, 1):
            md.append(f"### Question {idx} ({q.get('question_type', 'mcq').upper()})")
            md.append(f"{q.get('question_text')}\n")
            opts = q.get("options", [])
            if isinstance(opts, str):
                try:
                    opts = json.loads(opts)
                except Exception:
                    opts = []
            for opt in opts:
                md.append(f"- {opt}")
            md.append(f"\n**Correct Answer:** {q.get('correct_answer')}")
            md.append(f"**Explanation:** {q.get('explanation')}\n")

        # Transcript if present
        segments = lecture_data.get("segments", [])
        if segments:
            md.append("---\n## 🎙️ Transcript Record\n")
            for s in segments:
                start = f"{int(s.get('start_time', 0)) // 60:02d}:{int(s.get('start_time', 0)) % 60:02d}"
                md.append(f"**[{start}] {s.get('speaker', 'Speaker')}:** {s.get('text')}\n")

        return "\n".join(md)

    @staticmethod
    def to_json(lecture_data: Dict[str, Any]) -> str:
        """Exports raw lecture data package as formatted JSON."""
        return json.dumps(lecture_data, indent=2, default=str)

export_service = ExportService()
